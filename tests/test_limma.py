"""Tests for the moderated (limma-style) two-group t-test.

Parity tests compare against reference outputs generated by R limma
(``tests/tools/make_limma_fixtures.R`` -> ``tests/data/limma/``). R is not needed to run them.
"""

from pathlib import Path

import numpy as np
import pandas as pd
import pytest
import scipy.sparse
from scipy.special import polygamma

from scpviz import utils
from scpviz.utils.limma import _trigamma_inverse, moderated_two_group_test

FIXTURE_DIR = Path(__file__).parent / "data" / "limma"
CASES = [
    "balanced_4v4", "unbalanced_3v5", "missing_mixed_df", "missing_extreme",
    "zero_variance", "zero_variance_missing", "null_4v4", "shifted_4v4",
    "two_proteins", "three_proteins", "all_na", "no_residual_df",
]
LEGACY = {"NULL": None, "TRUE": True, "FALSE": False}
# Exactly-zero residual variances: R's QR fit leaves ~1e-30 floating-point noise (so they count as
# "positive" when limma sets the variance floor from the median of positive variances), whereas the
# sums of squares here are exactly 0. That shifts the unequal-df prior scale by ~4e-4 (relative).
# Not reproducible without replicating R's rounding; legacy-estimator results are unaffected.
ZERO_VAR_UNEQUAL_DF = {("zero_variance", "FALSE"), ("zero_variance_missing", "NULL"), ("zero_variance_missing", "FALSE")}


def _load(case):
    expr = pd.read_csv(FIXTURE_DIR / f"{case}_expr.csv", index_col=0, na_values="NA")
    group = pd.read_csv(FIXTURE_DIR / f"{case}_group.csv")["group"].to_numpy()
    return expr.loc[:, group == "g1"].T.to_numpy(float), expr.loc[:, group == "g2"].T.to_numpy(float), expr.index


def _close(actual, expected, rtol, atol=0.0):
    np.testing.assert_allclose(np.asarray(actual, float), np.asarray(expected, float), rtol=rtol, atol=atol, equal_nan=True)


@pytest.mark.parametrize("case", CASES)
@pytest.mark.parametrize("leg", list(LEGACY))
def test_limma_parity_with_r(case, leg):
    d1, d2, _ = _load(case)
    prior = pd.read_csv(FIXTURE_DIR / f"{case}_legacy{leg}_prior.csv")
    if prior.loc[0, "status"] == "error":
        with pytest.raises(ValueError, match="limma"):
            moderated_two_group_test(d1, d2, legacy=LEGACY[leg])
        return

    ref = pd.read_csv(FIXTURE_DIR / f"{case}_legacy{leg}_result.csv", na_values="NA")
    res = moderated_two_group_test(d1, d2, legacy=LEGACY[leg])

    # 1. OLS (exact up to floating point)
    _close(res["beta"], ref["coef"], 1e-9, atol=1e-12)
    _close(res["stdev_unscaled"], ref["stdev_unscaled"], 1e-9)
    _close(res["df_residual"], ref["df_residual"], 0)
    _close(res["s2"], ref["s2"], 1e-8, atol=1e-14)
    loose = (case, leg) in ZERO_VAR_UNEQUAL_DF
    tol = 2e-3 if loose else 1e-5
    # 2. prior and posterior variance
    if not np.isnan(prior.loc[0, "df_prior"]) and len(ref) >= 3:
        _close(res["df_prior"], prior.loc[0, "df_prior"], tol)
        _close(res["s2_prior"], prior.loc[0, "s2_prior"], tol)
    elif len(ref) < 3:
        assert res["df_prior"] == 0 and res["estimator"] == "none"
    _close(res["s2_post"], ref["s2_post"], tol, atol=1e-14)
    # 3. statistic, df, p-value, BH
    _close(res["t"], ref["t"], tol, atol=1e-10)
    _close(res["df_total"], ref["df_total"], tol)
    _close(res["p_value"], ref["p_value"], 10 * tol, atol=1e-12)
    _close(utils.bh_adjust_pvalues(res["p_value"]), ref["p_adj"], 10 * tol, atol=1e-12)


def test_limma_default_dispatch_follows_equal_df():
    d1, d2, _ = _load("balanced_4v4")
    assert moderated_two_group_test(d1, d2)["estimator"] == "legacy"
    d1, d2, _ = _load("missing_mixed_df")
    assert moderated_two_group_test(d1, d2)["estimator"] == "unequal_df"
    assert moderated_two_group_test(d1, d2, legacy=True)["estimator"] == "legacy"


def test_limma_sign_and_group_order():
    rng = np.random.default_rng(1)
    base = rng.normal(10, 1, (6, 50))
    g1, g2 = base.copy() + 3.0, base.copy()
    res = moderated_two_group_test(g1, g2)
    assert np.all(res["beta"] > 0)
    res_swapped = moderated_two_group_test(g2, g1)
    np.testing.assert_allclose(res_swapped["beta"], -res["beta"])
    np.testing.assert_allclose(res_swapped["p_value"], res["p_value"])


def test_limma_null_pvalues_roughly_uniform():
    d1, d2, _ = _load("null_4v4")
    p = moderated_two_group_test(d1, d2)["p_value"]
    assert abs(np.mean(p < 0.05) - 0.05) < 0.04


def test_limma_strong_shrinkage_when_variances_homogeneous():
    # variances drawn from one distribution -> little excess dispersion -> large prior df
    rng = np.random.default_rng(0)
    x = rng.normal(0, 1, (8, 200))
    res = moderated_two_group_test(x[:4], x[4:])
    assert np.isfinite(res["s2_prior"])
    assert res["df_prior"] > 10  # near-null dispersion -> strong shrinkage


def test_limma_feature_order_invariance():
    d1, d2, _ = _load("missing_mixed_df")
    perm = np.random.default_rng(3).permutation(d1.shape[1])
    a = moderated_two_group_test(d1, d2)
    b = moderated_two_group_test(d1[:, perm], d2[:, perm])
    np.testing.assert_allclose(a["p_value"][perm], b["p_value"], rtol=1e-6, equal_nan=True)
    assert a["df_prior"] == pytest.approx(b["df_prior"], rel=1e-6)


@pytest.mark.parametrize("x", [1e-8, 1e-3, 0.2, 1.0, 5.0, 1e3, 1e9])
def test_trigamma_inverse_roundtrip(x):
    y = _trigamma_inverse(x)
    assert polygamma(1, y) == pytest.approx(x, rel=1e-4)


def test_limma_raises_without_residual_df():
    x = np.ones((1, 5))  # 1 v 1 for every feature -> df = 0 everywhere
    with pytest.raises(ValueError, match="residual degrees of freedom"):
        moderated_two_group_test(x, x)


# --- integration with de_adata / pdata.de ---------------------------------------------------

def _adata(seed=0, n_prot=60, n_per_group=4, shift=2.0, n_shifted=6):
    from anndata import AnnData
    rng = np.random.default_rng(seed)
    X = rng.normal(15, 1, (2 * n_per_group, n_prot))
    X[:n_per_group, :n_shifted] += shift
    X[rng.random(X.shape) < 0.1] = np.nan
    obs = pd.DataFrame({"g": ["A"] * n_per_group + ["B"] * n_per_group})
    return AnnData(X=X, obs=obs)


def test_de_adata_limma_matches_core_function():
    ad_ = _adata(shift=5.0)
    values = [{"g": "A"}, {"g": "B"}]
    df = utils.de_adata(ad_, values=values, method="limma", data_is_log=True, correct_fdr=True)
    core = moderated_two_group_test(ad_.X[:4], ad_.X[4:])
    np.testing.assert_allclose(df["p_value"].to_numpy(), core["p_value"], equal_nan=True)
    np.testing.assert_allclose(df["test_statistic"].to_numpy(), core["t"], equal_nan=True)
    np.testing.assert_allclose(df["log2fc"].to_numpy(), core["beta"], equal_nan=True)  # log2 layer -> log2fc = beta
    assert df.attrs["limma"]["estimator"] in {"legacy", "unequal_df"}
    assert "adj_p_value" in df.columns
    assert (df["significance"].iloc[:6] == "upregulated").sum() >= 4  # shifted proteins are detected


def test_de_adata_limma_requires_log_and_mean_fc():
    ad_ = _adata()
    values = [{"g": "A"}, {"g": "B"}]
    with pytest.raises(ValueError, match="log-transformed"):
        utils.de_adata(ad_, values=values, method="limma", data_is_log=False)
    with pytest.raises(ValueError, match="fold_change_mode='mean'"):
        utils.de_adata(ad_, values=values, method="limma", data_is_log=True, fold_change_mode="pairwise_median")


def test_de_adata_limma_prints_prior_once(capsys):
    utils.de_adata(_adata(), values=[{"g": "A"}, {"g": "B"}], method="limma", data_is_log=True)
    out = capsys.readouterr().out
    assert out.count("prior estimator") == 1


def test_pdata_de_limma_validation(pdata):
    values = [{"cellline": "BE"}, {"cellline": "AS"}]
    with pytest.raises(ValueError, match="Unsupported test method"):
        pdata.de(values=values, method="bogus")
    with pytest.raises(ValueError, match="log-transformed"):
        pdata.de(values=values, method="limma", layer="X_raw")


def test_pdata_de_limma_on_log_layer(pdata):
    p = pdata.copy()
    p.log_transform(base=2, pseudocount=1.0)
    df = p.de(values=[{"cellline": "BE"}, {"cellline": "AS"}], method="limma", correct_fdr=True)
    assert np.isfinite(df["p_value"]).any() and np.isfinite(df["adj_p_value"]).any()
    assert df.attrs["limma"]["df_prior"] >= 0


def test_pdata_de_limma_log2fc_is_modeled_coefficient(pdata):
    p = pdata.copy()
    p.log_transform(base=2, pseudocount=1.0)
    df = p.de(values=[{"cellline": "BE"}, {"cellline": "AS"}], method="limma")
    ok = df["log2fc"].notna()
    # limma's coefficient is the log2 group-mean difference: sign agrees with the t-statistic
    assert (np.sign(df.loc[ok, "log2fc"]) == np.sign(df.loc[ok, "test_statistic"])).all()


@pytest.mark.parametrize("case,leg", sorted(ZERO_VAR_UNEQUAL_DF))
def test_unequal_df_prior_exact_given_rs_own_variances(case, leg):
    """Given R's own residual variances the estimator matches R tightly: the looser parity
    tolerance above comes only from the exact-zero variance inputs, not from the estimator."""
    from scpviz.utils.limma import _fit_fdist_unequal_df
    ref = pd.read_csv(FIXTURE_DIR / f"{case}_legacy{leg}_result.csv", na_values="NA")
    prior = pd.read_csv(FIXTURE_DIR / f"{case}_legacy{leg}_prior.csv")
    df = ref["df_residual"].to_numpy(float)
    s0, d0 = _fit_fdist_unequal_df(np.where(df == 0, 0.0, ref["s2"].to_numpy(float)), df)
    assert d0 == pytest.approx(prior.loc[0, "df_prior"], rel=1e-7)
    assert s0 == pytest.approx(prior.loc[0, "s2_prior"], rel=1e-7)


def test_limma_ignores_min_valid_fraction_de_adata(capsys):
    ad_ = _adata(shift=5.0)
    ad_.X[:3, 0] = np.nan  # protein 0: 1 of 4 valid values in group A
    df = utils.de_adata(ad_, values=[{"g": "A"}, {"g": "B"}], method="limma", data_is_log=True, correct_fdr=True)
    assert "excluded from FDR correction" not in capsys.readouterr().out
    np.testing.assert_allclose(df["adj_p_value"].to_numpy(), utils.bh_adjust_pvalues(df["p_value"].to_numpy()), equal_nan=True)


def test_limma_ignores_min_valid_fraction_pdata_de(pdata, capsys):
    p = pdata.copy()
    p.log_transform(base=2, pseudocount=1.0)
    X = p.prot.X.toarray() if scipy.sparse.issparse(p.prot.X) else np.array(p.prot.X, dtype=float)
    be = np.where(p.prot.obs["cellline"].to_numpy() == "BE")[0]
    X[be[:-1], 0] = np.nan  # protein 0 nearly absent from BE
    p.prot.X = X
    df = p.de(values=[{"cellline": "BE"}, {"cellline": "AS"}], method="limma", correct_fdr=True)
    assert "excluded from FDR correction" not in capsys.readouterr().out
    np.testing.assert_allclose(df["adj_p_value"].to_numpy(), utils.bh_adjust_pvalues(df["p_value"].to_numpy()), equal_nan=True)


def test_limma_stats_survive_save_load(pdata, tmp_path):
    from scpviz import pAnnData
    p = pdata.copy()
    p.log_transform(base=2, pseudocount=1.0)
    p.de(values=[{"cellline": "BE"}, {"cellline": "AS"}], method="limma")
    path = tmp_path / "limma_roundtrip.pdata"
    p.save(path)
    loaded = pAnnData.load(path)
    key = next(iter(p.stats))
    pd.testing.assert_frame_equal(loaded.stats[key], p.stats[key], check_categorical=False)


def test_plot_volcano_with_limma(pdata):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from scpviz import plotting as scplt
    p = pdata.copy()
    p.log_transform(base=2, pseudocount=1.0)
    values = [{"cellline": "BE"}, {"cellline": "AS"}]
    fig, ax = plt.subplots()
    # inline DE with method='limma'
    scplt.plot_volcano(ax, p, values=values, method="limma", correct_fdr=True, label=0)
    assert len(ax.collections) > 0
    plt.close(fig)
    # from a stored limma result
    p.de(values=values, method="limma", correct_fdr=True)
    key = next(iter(p.stats))
    fig, ax = plt.subplots()
    scplt.plot_volcano(ax, p, stats_key=key, correct_fdr=True, label=0)
    assert len(ax.collections) > 0
    plt.close(fig)
